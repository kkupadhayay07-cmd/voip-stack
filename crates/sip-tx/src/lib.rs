#![forbid(unsafe_code)]
//! # sip-tx — RFC 3261 transaction state machines
//!
//! Pure transaction-layer state machines (RFC 3261 §17). **No I/O, no async
//! runtime, no sockets, no threads.** The only dependency is [`sip-core`]
//! for the message types. Callers drive time and events:
//!
//! * feed wire events with [`TxEvent`] via [`ClientTx::on_event`]-style
//!   methods,
//! * poll [`next_deadline`](ClientInviteTx::next_deadline) and deliver
//!   [`TxEvent::Timeout`] when that instant passes (a fake clock in tests,
//!   a real timer in production),
//! * execute every returned [`TxAction`] — the state machines never touch
//!   the network themselves.
//!
//! Because all time enters through `now: Instant` parameters, every timer
//! transition is unit-testable with a hand-rolled fake clock.
//!
//! # Timers (RFC 3261 §17.1.1.2 / §17.1.2.2)
//!
//! Defaults per [`TimerConfig`]: T1 = 500 ms, T2 = 4 s, T4 = 5 s.
//! Derivations: Timer A/E/G start at T1 and double per fire (E/G capped at
//! T2); B/F/H = 64·T1; D = max(32 s, 64·T1); I/K = T4; J = 64·T1. Reliable
//! transports (TCP/TLS/WS/WSS) suppress the retransmission timers A/E/G and
//! collapse D/I/K to zero.
//!
//! # Transactions
//!
//! | Type | RFC section |
//! |------|-------------|
//! | [`ClientInviteTx`] | §17.1.1 |
//! | [`ClientNonInviteTx`] | §17.1.2 |
//! | [`ServerInviteTx`] | §17.2.1 |
//! | [`ServerNonInviteTx`] | §17.2.2 |
//!
//! Matching (RFC 3261 §17.1.3 / §17.2.3): responses match on top-Via
//! branch + sent-by + CSeq (method and number); an ACK for a 2xx is a
//! separate transaction and never matches the INVITE transaction state
//! machine; an ACK for a non-2xx final response is generated by
//! [`ClientInviteTx`] itself (§17.1.1) and matched by
//! [`ServerInviteTx`] via [`matching::ack_matches_invite`].

